"""Numbers and merged table for arXiv v5 (final checks of arXiv v4, 2026-11-25). Run from this folder (stdlib only): python3 make_numbers_v8.py
Reads results/truth_d*_p*.json + truthextra_d*_p*.json (run-to-run z of the twelve reference cells) and writes numbers_v8.tex, numbers_v8.json
(keys v8.*) and tab_v8_cov.tex (SM Tables S9+S10 merged: hit fraction, reference range and Clopper-Pearson interval per cell, from the v7 keys)."""
import json, glob, math, re
R = "../results"; V = {}
def put(k, v, src, how=""):
    assert re.fullmatch(r"[A-Za-z0-9.]+", k) and k not in V, k
    V[k] = (str(v), src, how)
TG = ["0.001", "0.0001", "1e-05", "1e-06"]; tn = dict(zip(TG, "3456"))
T = {}
for f in glob.glob(f"{R}/truth_d*_p*.json"):
    x = json.load(open(f)); T[(x["d"], x["p"])] = x
zs = {}
for f in glob.glob(f"{R}/truthextra_d*_p*.json"):
    y = json.load(open(f)); x = T[(y["d"], y["p"])]
    zs[(x["d"], x["p"])] = (x["truth"] - y["truth"]) / math.hypot(x["se"], y["se"])
assert len(zs) == 12
for (d, p), z in zs.items():
    put(f"v8.z.d{d}.t{tn['%g' % p if False else [t for t in TG if abs(float(t)-p)<1e-12][0]]}", f"{z:+.2f}", "results/truth_*, truthextra_*", "run 1 minus run 2 over combined se")
kmax = max(zs, key=lambda k: abs(zs[k])); assert f"{abs(zs[kmax]):.2f}" == "1.64" and kmax == (3, 1e-4)
NAME = dict(R1="R1", R2="R2", R3="R3", R4p="R4$'$", R5="R5")
ROWS = [(rc, d) for rc in ("R2", "R3", "R1", "R4p") for d in (3, 5, 7)] + [("R5", 7)]
with open("tab_v8_cov.tex", "w") as f:
    f.write("\\begin{tabular}{llllll}\\hline\\hline\nrecipe & $d$ & $10^{-3}$ & $10^{-4}$ & $10^{-5}$ & $10^{-6}$\\\\\\hline\n")
    for w, wn in (("w1", "First window"), ("w2", "Second window")):
        f.write(f"\\multicolumn{{6}}{{l}}{{\\emph{{{wn}}}}}\\\\\n")
        for rc, d in ROWS:
            f.write(f"{NAME[rc]} & {d}" + "".join(f" & \\V{{v7.k.{w}.{rc}.d{d}.t{tn[t]}}}; \\V{{v7.cv.{w}.{rc}.d{d}.t{tn[t]}}} (\\V{{v7.rg.{w}.{rc}.d{d}.t{tn[t]}}}) [\\V{{v7.cp.{w}.{rc}.d{d}.t{tn[t]}}}]" for t in TG) + "\\\\\n")
    f.write("\\hline\\hline\n\\end{tabular}\n")
with open("numbers_v8.tex", "w") as f:
    f.write("% GENERATED by make_numbers_v8.py. Do not edit. Input after numbers_v7.tex.\n")
    for k, (v, s, h) in V.items(): f.write(f"\\expandafter\\def\\csname LV@{k}\\endcsname{{{v}}}\n")
json.dump({k: dict(value=v, source=s, how=h) for k, (v, s, h) in V.items()}, open("numbers_v8.json", "w"), indent=1)
print(len(V), "keys")
